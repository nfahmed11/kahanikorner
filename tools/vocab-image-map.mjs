#!/usr/bin/env node
/*
 * Kahani Korner — write the vocabulary image map used by the Urdu games.
 *
 *   node tools/vocab-image-map.mjs           # (re)write qr/assets/js/vocab-images.js
 *   node tools/vocab-image-map.mjs --check   # exit 1 if the map is stale or an image
 *                                            # has no WebP copies yet
 *
 * Run after tools/optimize-images.sh. For every folder entry in tools/images.conf
 * whose files live under qr/ (e.g. "v-* | ../../qr/assets/images/*.png"), it maps
 * each original PNG URL to its generated WebP copies in assets/images/opt/, using
 * the same naming rule as optimize-images.sh (<prefix><slug>-<sha1(filename)[0:6]>).
 * Games keep the PNG URLs from mastervocab.js unchanged and look them up here.
 * Never edits HTML or mastervocab.js.
 */
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const IMG = path.join(ROOT, "assets/images");
const OPT = path.join(IMG, "opt");
const OUT = path.join(ROOT, "qr/assets/js/vocab-images.js");
const CHECK = process.argv.includes("--check");
const PNG_SIG = "89504e470d0a1a0a";

const die = (m) => { console.error(`error: ${m}`); process.exit(1); };
const conf = fs.readFileSync(path.join(ROOT, "tools/images.conf"), "utf8").split("\n")
  .map((l) => l.trim()).filter((l) => l && !l.startsWith("#")).map((l) => l.split("|").map((s) => s.trim()))
  .filter(([name, src]) => name.endsWith("*") && /qr\//.test(src));
if (!conf.length) die("no qr/ folder entry found in tools/images.conf");

const opt = fs.readdirSync(OPT);
const map = {};
const missing = [];
let skipped = 0;
for (const [name, src] of conf) {
  const prefix = name.slice(0, -1);
  const dir = path.join(IMG, path.dirname(src));
  const re = new RegExp(`^${path.basename(src).replace(/[.+^${}()|[\]\\]/g, "\\$&").replace(/\*/g, ".*")}$`);
  for (const base of fs.readdirSync(dir).filter((f) => re.test(f)).sort()) {
    const file = path.join(dir, base);
    if (fs.readFileSync(file).subarray(0, 8).toString("hex") !== PNG_SIG) { skipped++; continue; } // damaged, skipped by the generator too
    const slug = base.replace(/\.[^.]*$/, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
    const id = createHash("sha1").update(base).digest("hex").slice(0, 6);
    const stem = `${prefix}${slug}-${id}`;
    const variants = opt.map((f) => f.match(new RegExp(`^${stem}-(\\d+)\\.[0-9a-f]{8}\\.webp$`))).filter(Boolean)
      .map((m) => ({ f: m[0], w: +m[1] })).sort((a, b) => a.w - b.w);
    // Several hashes for one width = older copies kept for caches; use the newest file.
    const byWidth = new Map();
    for (const v of variants) {
      const prev = byWidth.get(v.w);
      if (!prev || fs.statSync(path.join(OPT, v.f)).mtimeMs > fs.statSync(path.join(OPT, prev.f)).mtimeMs) byWidth.set(v.w, v);
    }
    if (!byWidth.size) { missing.push(base); continue; }
    const url = "/" + path.relative(ROOT, file).split(path.sep).join("/");
    map[url] = [...byWidth.values()].map((v) => `/assets/images/opt/${v.f} ${v.w}w`).join(", ");
  }
}

const js = `// GENERATED by tools/vocab-image-map.mjs — do not edit by hand.
// Original vocabulary PNG URL -> srcset of its optimized WebP copies.
export const VOCAB_WEBP = ${JSON.stringify(map, null, 1)};

// srcset for a vocabulary image URL, or "" if it has no optimized copy.
export function vocabSrcset(url) {
  return VOCAB_WEBP[url] || "";
}

// Point an <img> at the optimized copies, keeping the PNG as src. If the WebP
// can't be shown, drop srcset so the browser falls back to the PNG.
export function useVocabImage(img, url, sizes) {
  const srcset = vocabSrcset(url);
  if (srcset) {
    img.addEventListener("error", function fallback() {
      if (img.hasAttribute("srcset")) { img.removeAttribute("srcset"); img.src = url; }
      img.removeEventListener("error", fallback);
    });
    img.sizes = sizes;
    img.srcset = srcset;
  }
  img.src = url;
}
`;

const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
console.log(`${Object.keys(map).length} images mapped, ${missing.length} without WebP copies, ${skipped} damaged files skipped`);
if (missing.length) console.log(`no WebP copies yet (run tools/optimize-images.sh): ${missing.slice(0, 10).join(", ")}${missing.length > 10 ? " …" : ""}`);
if (CHECK) {
  if (current !== js || missing.length) { console.log("OUT OF DATE — run node tools/vocab-image-map.mjs"); process.exit(1); }
  console.log("vocab image map is up to date");
  process.exit(0);
}
if (current !== js) { fs.writeFileSync(OUT, js); console.log(`wrote ${path.relative(ROOT, OUT)}`); } else console.log("already up to date");
